#!/usr/bin/env python3
"""Writes Gutter's Hyprland Lua override from palette.json.

Usage: hypr.py [--palette PATH] [--out PATH] [--mode light|dark] [--config PATH]
The output is `require`d by hypr/gutter.lua after the repo's own modules and before the user's hypr-user.lua, so it
overrides their values and window rules. It never sets gaps. --out defaults to
${XDG_STATE_HOME:-~/.local/state}/gutter/hypr-gutter.lua. The window shadow is in the colour shadow.color names in
Gutter's config.json (teal when it names none, or the file is missing or invalid). Exit 0 writes the file
atomically; exit 1 leaves the target untouched and prints "hypr: <reason>" on stderr. A version 1 palette is
upgraded in memory (the file is not rewritten).
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

from atomicio import write_atomic

ROOT = Path(__file__).resolve().parents[1]
BORDER_SIZE = 3
SHADOW_OFFSET = "6 6"
# The names shadow.color takes, as lib/palette.js has them: the ink, an accent, or a role.
ACCENTS = ("navy", "teal", "magenta", "coral", "sun", "lime", "pink")
ROLES = ("active", "urgent", "focusBorder", "ok", "special", "muted")
SHADOW_COLOURS = ("ink",) + ACCENTS + ROLES
DEFAULT_SHADOW = "teal"
HEX_COLOUR = re.compile(r"#[0-9a-fA-F]{6}")

TEMPLATE = """\
-- Generated by Gutter (tools/hypr.py) from the palette. Do not edit; rerun the generator instead.
-- Ink borders, no rounding, hard offset shadow, no blur. Gutter never sets gaps.

hl.config({{
    general = {{
        border_size = {border_size},

        col = {{
            active_border = "{active}",
            inactive_border = "{inactive}",
        }},
    }},

    group = {{
        col = {{
            border_active = "{active}",
            border_inactive = "{inactive}",
            border_locked_active = "{active}",
            border_locked_inactive = "{inactive}",
        }},

        groupbar = {{
            text_color = "{inactive}",

            col = {{
                active = "{active}",
                inactive = "{muted}",
                locked_active = "{active}",
                locked_inactive = "{muted}",
            }},
        }},
    }},

    decoration = {{
        rounding = 0,

        blur = {{
            enabled = false,
        }},

        shadow = {{
            enabled = true,
            range = 1,
            sharp = true,
            offset = "{offset}",
            color = "{shadow}",
        }},
    }},

    animations = {{
        enabled = true,
    }},
}})

-- Short ease-out slides
hl.curve("gutterOut", {{ type = "bezier", points = {{ {{ 0.0, 0.0 }}, {{ 0.2, 1.0 }} }} }})

-- The windowsIn/Out/Move children are set explicitly too, because an explicit child beats the parent leaf.
hl.animation({{ leaf = "windows", enabled = true, speed = 2, bezier = "gutterOut", style = "slide" }})
hl.animation({{ leaf = "windowsIn", enabled = true, speed = 2, bezier = "gutterOut", style = "slide" }})
hl.animation({{ leaf = "windowsOut", enabled = true, speed = 2, bezier = "gutterOut", style = "slide" }})
hl.animation({{ leaf = "windowsMove", enabled = true, speed = 2, bezier = "gutterOut", style = "slide" }})
hl.animation({{ leaf = "workspaces", enabled = true, speed = 2, bezier = "gutterOut", style = "slide" }})
hl.animation({{ leaf = "fade", enabled = true, speed = 1, bezier = "gutterOut" }})

-- Opacity and rounding as window rules, which beat the plain config values above (and any rule set earlier).
hl.window_rule({{ match = {{ fullscreen = false }}, opacity = "1.0 override" }})
hl.window_rule({{ match = {{ fullscreen = false }}, rounding = 0 }})
"""


def _hex(colour):
    """'#RRGGBB' -> 'rrggbb' (Hyprland colour strings are lowercase without the hash)."""
    return colour.lstrip("#").lower()


def shadow_colour(half, roles, name):
    """The shadow's '#rrggbb' in one half of the palette: its ink, an accent, or the accent a role maps to."""
    if name == "ink":
        return half["ink"]
    return half["accents"][roles[name] if name in ROLES else name]


def check(palette, mode, shadow=DEFAULT_SHADOW):
    """Raises ValueError naming the first colour render() would use that is missing from a version 2 palette's `mode`
    half or is not #RRGGBB (Hyprland would read `rgb(abc)` as something else). Colours render() does not use are not
    checked."""
    try:
        roles, half = palette["roles"], palette[mode]
        colours = {"%s.ink" % mode: half["ink"]}
        for role in ("focusBorder", "muted"):
            colours["%s.accents.%s" % (mode, roles[role])] = half["accents"][roles[role]]
        colours["%s shadow colour %s" % (mode, shadow)] = shadow_colour(half, roles, shadow)
    except KeyError as e:
        raise ValueError("missing key %s" % e)
    except (TypeError, AttributeError):
        raise ValueError("not a palette")
    for where, colour in colours.items():
        if not (isinstance(colour, str) and HEX_COLOUR.fullmatch(colour)):
            raise ValueError("%s is not #RRGGBB: %r" % (where, colour))


def render(palette, mode="light", shadow=DEFAULT_SHADOW):
    """The Lua override for one half of a checked palette."""
    roles, half = palette["roles"], palette[mode]
    return TEMPLATE.format(
        border_size=BORDER_SIZE,
        active="rgb(%s)" % _hex(half["accents"][roles["focusBorder"]]),
        inactive="rgb(%s)" % _hex(half["ink"]),
        muted="rgb(%s)" % _hex(half["accents"][roles["muted"]]),
        offset=SHADOW_OFFSET,
        shadow="rgba(%sff)" % _hex(shadow_colour(half, roles, shadow)),
    )


# --- command line -------------------------------------------------------------------------------

def default_palette():
    state = os.environ.get("XDG_STATE_HOME") or os.path.expanduser("~/.local/state")
    live = Path(state) / "gutter" / "palette.json"
    return live if live.exists() else ROOT / "theme" / "default-palette.json"


def default_out():
    state = os.environ.get("XDG_STATE_HOME") or os.path.expanduser("~/.local/state")
    return Path(state) / "gutter" / "hypr-gutter.lua"


def default_config():
    base = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
    return Path(base) / "gutter" / "config.json"


def shadow_name(path):
    """shadow.color from Gutter's config.json, or teal when the file is missing, unreadable or invalid, or
    names no known colour. Never raises: the shell warns about a bad setting, Hyprland just gets the default."""
    try:
        name = json.loads(Path(path).read_text())["shadow"]["color"]
    except (OSError, ValueError, KeyError, TypeError):
        return DEFAULT_SHADOW
    return name if name in SHADOW_COLOURS else DEFAULT_SHADOW


def load(src):
    """The palette file as a version 2 dict; version 1 is upgraded in memory against the default palette."""
    pal = json.loads(src.read_text())
    try:
        version = pal["version"]
    except (KeyError, TypeError):
        raise ValueError("no palette version")
    if type(version) is not int or version not in (1, 2):      # not True or 1.0, which compare equal to 1
        raise ValueError("unknown palette version %r" % (version,))
    if version == 1:
        import palette  # numpy and PIL only load when an old file needs upgrading
        try:
            pal = palette.upgrade(pal, palette.load_default(ROOT / "theme" / "default-palette.json"))
        except palette.PaletteError as e:
            raise ValueError(str(e))
        except ValueError as e:     # a colour that is not #RRGGBB, from hex_to_rgb
            raise ValueError("cannot upgrade version 1: a colour is not #RRGGBB (%s)" % e)
        except (KeyError, TypeError, AttributeError) as e:
            raise ValueError("cannot upgrade version 1: %s" % palette.describe_error(e))
    return pal


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write Gutter's Hyprland Lua override from the palette.")
    ap.add_argument("--palette", type=Path, default=None)
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--mode", choices=("light", "dark"), default="light")
    ap.add_argument("--config", type=Path, default=None)
    args = ap.parse_args(argv)
    src = args.palette or default_palette()
    shadow = shadow_name(args.config or default_config())
    try:
        try:
            pal = load(src)
            check(pal, args.mode, shadow)
        except OSError as e:
            raise OSError("cannot read palette %s: %s" % (src, e.strerror or e))
        except ValueError as e:
            raise OSError("cannot use palette %s: %s" % (src, e))
        write_atomic(args.out or default_out(), render(pal, args.mode, shadow), ".hypr-gutter-")
    except OSError as e:
        print("hypr: %s" % e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
